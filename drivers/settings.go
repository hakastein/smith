package drivers

// Settings — программа драйвера и её окружение: настройки сервиса, общие для всех запусков драйвера.
type Settings struct {
	Bin string
	Env [][2]string // переменные сверх белого списка, по порядку
	// Readable — каталоги, открытые строгой песочнице всегда: сам драйвер и его рантайм.
	Readable []string
}
